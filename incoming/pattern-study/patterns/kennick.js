// The timelines, in ticks of 1/60 s at speed 1. The pounce's strike covers
// 2.0 s and its recovery 2.33 s; the bite's coil, strike and recovery cover
// 3.67, 4.0 and 4.33 s. Each knob position puts its first strike on 2.0 s.
// Every rest is a whole number of 8-tick rest cells.
const SEQ = [
  [["idle", 72], ["ready1", 8], ["tele1", 34], ["hit1", 16], ["rec1", 20], ["idle", 48], ["ready2", 8], ["tele2", 30], ["hit2", 16], ["rec2", 20], ["idle", 16]],
  [["idle", 72], ["ready1", 8], ["tele1", 34], ["hit1", 16], ["rec1", 20]],
  [["idle", 72], ["ready2", 8], ["tele2", 34], ["hit2", 16], ["rec2", 20]],
];
// The rest cells: the upper body sinks a pixel on the breath and the tail
// tip follows a cell behind.
const IDLE = [["idle", 0], ["idle1", 0], ["idle1", 1], ["idle", 1], ["idle2", 1], ["idle2", 0]];
const IDLE_TICKS = 8;
const BREATH_ROW = 37;
const EMPTY = ".".repeat(AW);

const { floor, min, max } = Math;

function cellAt(t, mode) {
  const seq = SEQ[mode];
  let len = 0;
  for (const s of seq) len += s[1];
  const tick = floor(t * 60 + 1e-6);
  let u = tick % len;
  for (const [name, n] of seq) {
    if (u < n) {
      if (name !== "idle") return [name, 0];
      return IDLE[floor(u / IDLE_TICKS) % IDLE.length];
    }
    u -= n;
  }
  return ["idle", 0];
}

function lut(paint) {
  const t = new Int32Array(128).fill(-1);
  const p = PAINTS[paint];
  for (const k in p) t[k.charCodeAt(0)] = p[k];
  t[88] = 0; // X
  return t;
}

export function setup(params) {
  params.t = 0;
  params.mode = 0;
  params.speed = 1;
  params.paint = 0;
  params.flip = 0;
  params.key = -1;
}

export function update(dt, input, params) {
  if (params.key === undefined) setup(params);
  const k = input.knobValues || [0, 2, 0, 0.06];
  params.mode = min(2, max(0, floor(k[0])));
  params.speed = min(3, max(0.5, k[1])) / 2;
  params.paint = min(3, max(0, floor(k[2] * 4)));
  params.flip = k[3] >= 0.5 ? 1 : 0;
  params.t += min(dt || 0, 0.1) * params.speed;
}

export function draw(display, params) {
  const p = params;
  if (p.key === undefined) setup(p);
  if (p.key !== p.paint) {
    p.key = p.paint;
    p.lut = lut(p.paint);
  }
  const L = p.lut;
  const [name, dy] = cellAt(p.t, p.mode);
  const rows = CELLS[name];
  for (let y = 0; y < H; y++) {
    let j = y >> 1;
    if (dy && j <= BREATH_ROW + 1) j -= 1;
    const row = j < 0 ? EMPTY : rows[j];
    for (let x = 0; x < W; x++) {
      const i = p.flip ? AW - 1 - (x >> 1) : x >> 1;
      const ch = row.charCodeAt(i);
      if (ch === 46) {
        display.setPixel(x, y, 0, 0, 0);
        continue;
      }
      const c = L[ch];
      if (c < 0) display.setPixel(x, y, 255, 0, 255);
      else display.setPixel(x, y, (c >> 16) & 255, (c >> 8) & 255, c & 255);
    }
  }
}
