// Timing in ticks of 1/60 s. The thrust holds from 1.87 to 2.13 s and its
// second recovery cell covers 2.33 s; the pin's wind-up covers 3.67 s, the
// pin itself 4.0 s and its recovery 4.33 s. Rest cells count from the end of
// the last action, so no rest cell is cut to a single frame.
const REST = [["I0", 10], ["I1", 10], ["I2", 10], ["I3", 10]];
const LUNGE = [["LA1", 8], ["LA2", 8], ["LH", 16], ["LR1", 8], ["LR2", 12]];
const PIN = [["PA1", 8], ["PA2", 8], ["PH", 16], ["PR1", 8], ["LR2", 14]];
const START = 96;          // the first action starts at 1.6 s
const PLANS = [
  { loop: 256, acts: [[LUNGE, 0], [PIN, 122]] },   // lunge at 1.6 s, pin at 3.63 s, 4.27 s loop
  { loop: 130, acts: [[LUNGE, 0]] },
  { loop: 130, acts: [[PIN, 0]] },
];
const LEN = (seq) => seq.reduce((a, c) => a + c[1], 0);

const { floor, min, max } = Math;

function play(seq, at) {
  for (let i = 0; i < seq.length; i++) {
    if (at < seq[i][1]) return seq[i][0];
    at -= seq[i][1];
  }
  return null;
}
function rest(at) {
  return REST[floor(at / 10) % REST.length][0];
}
function cellAt(tick, action) {
  if (tick < START) return rest(tick);
  const plan = PLANS[action];
  const u = (tick - START) % plan.loop;
  let since = u + plan.loop - (plan.acts[plan.acts.length - 1][1] + LEN(plan.acts[plan.acts.length - 1][0]));
  for (const [seq, at] of plan.acts) {
    if (u >= at && u < at + LEN(seq)) return play(seq, u - at);
    if (u >= at + LEN(seq)) since = u - at - LEN(seq);
  }
  return rest(since);
}

export function setup(params) {
  params.t = 0;
  params.action = 0;
  params.speed = 1;
  params.flip = false;
  params.bg = 0;
}

export function update(dt, input, params) {
  if (params.t === undefined) setup(params);
  const k = input.knobValues || [0, 2, 0, 0.06];
  params.action = min(2, max(0, floor(k[0])));
  params.speed = min(3, max(0.5, k[1])) / 2;
  params.flip = k[2] >= 0.5;
  params.bg = min(3, max(0, floor(k[3] * 4)));
  params.t += min(dt || 0, 0.1) * params.speed;
}

export function draw(display, params) {
  const p = params;
  if (p.t === undefined) setup(p);
  const bg = BACKDROPS[p.bg];
  const br = (bg >> 16) & 255, bgg = (bg >> 8) & 255, bb = bg & 255;
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) display.setPixel(x, y, br, bgg, bb);
  const cell = CELLS[cellAt(floor(p.t * 60 + 1e-6), p.action)];
  const rows = cell.rows;
  for (let j = 0; j < rows.length; j++) {
    const r = rows[j];
    const y = (cell.y + j) * 2;
    for (let i = 0; i < r.length; i++) {
      const ch = r[i];
      if (ch === ".") continue;
      const c = PAL[ch];
      const ax = cell.x + i;
      const x = (p.flip ? 31 - ax : ax) * 2;
      const cr = c === undefined ? 255 : (c >> 16) & 255;
      const cg = c === undefined ? 0 : (c >> 8) & 255;
      const cb = c === undefined ? 255 : c & 255;
      display.setPixel(x, y, cr, cg, cb);
      display.setPixel(x + 1, y, cr, cg, cb);
      display.setPixel(x, y + 1, cr, cg, cb);
      display.setPixel(x + 1, y + 1, cr, cg, cb);
    }
  }
}
