/**
 * gen:shared: writes shared/constants.json out as the two files that read it,
 * firmware/patternflow/src/core_shared.h and web/src/lib/shared/constants.ts
 * (docs/rfc-cleanup.md §2.5). The lab counted 20 detents a turn until 31 July
 * 2026, against the encoder's 24, and the community sandbox until 4 September.
 * Each copy was found and fixed by hand.
 *
 * A key in the JSON is the constant's name on both sides: DETENTS_PER_TURN is
 * PF_SHARED_DETENTS_PER_TURN in the header and DETENTS_PER_TURN in the module.
 * The prefix keeps the macros clear of the names config.h already defines, and
 * of every feature's PF_<NAME>_ flags, which check_boundaries.py refuses in
 * src/. A key "//" is a note, and each group's note goes over its lines.
 *
 * check:shared (scripts/drift/shared.ts) imports render() and compares, so the
 * files on disk must be exactly what this writes.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const SOURCE = "shared/constants.json";
export const HEADER = "firmware/patternflow/src/core_shared.h";
export const MODULE = "web/src/lib/shared/constants.ts";

type Group = Record<string, unknown>;

const fail = (what: string): never => {
  throw new Error(`${SOURCE}: ${what}`);
};
const whole = (v: unknown, at: string) =>
  Number.isInteger(v) && (v as number) > 0 ? (v as number) : fail(`${at} is ${JSON.stringify(v)}, not a whole number above 0`);

/** A note as comment lines, wrapped at 80 columns. */
function comment(note: unknown): string[] {
  if (typeof note !== "string") return [];
  const lines: string[] = [];
  let line = "//";
  for (const word of note.split(/\s+/)) {
    if (line !== "//" && line.length + 1 + word.length > 80) {
      lines.push(line);
      line = "//";
    }
    line += ` ${word}`;
  }
  return [...lines, line];
}

const BANNER = [
  `// GENERATED by web/scripts/gen-shared.ts from ${SOURCE}. Do not edit.`,
  ...comment("Change the JSON and run `npm run gen:shared` in web/. check:shared fails while this file says anything else."),
];

/** Both files as gen:shared writes them, keyed by their path from the repository root. */
export function render(json = fs.readFileSync(path.join(ROOT, SOURCE), "utf8")): Record<string, string> {
  const data = JSON.parse(json) as Record<string, Group>;
  const h = [...BANNER, "//", "// License: MIT", "#pragma once"];
  const ts = [...BANNER];
  const names = new Set(["PANEL_GEOMETRIES", "PANEL_GEOM_DEFAULT"]);

  const panel = data.panel ?? fail("no panel group");
  const geometries = Object.entries((panel.PANEL_GEOMETRIES ?? fail("no panel.PANEL_GEOMETRIES")) as Record<string, Group>);
  const fallback = panel.PANEL_GEOM_DEFAULT;
  if (!geometries.some(([name]) => name === fallback)) fail(`panel.PANEL_GEOM_DEFAULT ${JSON.stringify(fallback)} is not in PANEL_GEOMETRIES`);
  const ids = new Set<number>();
  h.push("", ...comment(panel["//"]));
  ts.push("", ...comment(panel["//"]), "export const PANEL_GEOMETRIES = {");
  for (const [name, g] of geometries) {
    if (!/^\w+$/.test(name)) fail(`the geometry ${JSON.stringify(name)} is not a C name`);
    const at = `panel.PANEL_GEOMETRIES.${name}`;
    const [id, physW, physH, chain] = (["id", "physW", "physH", "chain"] as const).map((k) => whole(g[k], `${at}.${k}`));
    if (ids.has(id)) fail(`${at}.id ${id} is taken by another geometry`);
    ids.add(id);
    // config.h refuses a build where these two disagree with the physical size.
    const fields = { physW, physH, chain, resW: physW * chain, resH: physH };
    h.push(`#define PF_SHARED_PANEL_GEOM_${name} ${id}`);
    for (const [k, v] of Object.entries(fields)) h.push(`#define PF_SHARED_PANEL_GEOM_${name}_${k.replace(/[A-Z]/g, "_$&").toUpperCase()} ${v}`);
    ts.push(`  "${name}": { id: ${id}, ${Object.entries(fields).map(([k, v]) => `${k}: ${v}`).join(", ")} },`);
  }
  h.push(`#define PF_SHARED_PANEL_GEOM_DEFAULT PF_SHARED_PANEL_GEOM_${fallback}`);
  ts.push("} as const;", `export const PANEL_GEOM_DEFAULT = "${fallback}";`);

  for (const [group, values] of Object.entries(data)) {
    if (group === "//" || group === "panel") continue;
    h.push("", ...comment(values["//"]));
    ts.push("", ...comment(values["//"]));
    for (const [name, v] of Object.entries(values)) {
      if (name === "//") continue;
      if (!/^[A-Z][A-Z0-9_]*$/.test(name)) fail(`${group}.${name} is not a constant's name`);
      if (names.has(name)) fail(`${group}.${name} is named twice`);
      names.add(name);
      const n = whole(v, `${group}.${name}`);
      h.push(`#define PF_SHARED_${name} ${n}`);
      ts.push(`export const ${name} = ${n};`);
    }
  }
  return { [HEADER]: `${h.join("\n")}\n`, [MODULE]: `${ts.join("\n")}\n` };
}

if (path.resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
  for (const [file, text] of Object.entries(render())) {
    fs.mkdirSync(path.dirname(path.join(ROOT, file)), { recursive: true });
    fs.writeFileSync(path.join(ROOT, file), text);
    console.log(`wrote ${file}`);
  }
}
